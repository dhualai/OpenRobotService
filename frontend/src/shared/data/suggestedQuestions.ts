/** 随机抽取 n 条（Fisher–Yates 洗牌），用于空输入时的默认推荐 */
export function pickRandomQuestions(n: number): string[] {
  const copy = [...SUGGESTED_QUESTIONS];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.slice(0, n);
}

/** 按关键字检索（包含匹配），返回最多 max 条 */
export function matchQuestions(keyword: string, max = 8): string[] {
  const kw = keyword.trim();
  if (!kw) return [];
  return SUGGESTED_QUESTIONS.filter((q) => q.includes(kw)).slice(0, max);
}
