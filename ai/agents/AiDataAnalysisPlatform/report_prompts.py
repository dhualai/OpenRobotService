def build_report_system_prompt(
    period: ReportPeriod,
    scope: ReportScope = ReportScope.GLOBAL,
) -> str:
    """根据报告周期与数据范围返回对应的系统提示词。

    scope 决定模板族：
    - SINGLE_PROJECT → 单项目模板（章节围绕唯一项目展开）
    - USER_PROJECTS / GLOBAL → 多项目模板（统计范围的区分由用户消息中的
      数据范围说明完成，章节结构相同）
    """
    if scope == ReportScope.SINGLE_PROJECT:
        if period == ReportPeriod.WEEKLY:
            return WEEKLY_REPORT_SINGLE_PROJECT_SYSTEM_PROMPT
        return DAILY_REPORT_SINGLE_PROJECT_SYSTEM_PROMPT
    if period == ReportPeriod.WEEKLY:
        return WEEKLY_REPORT_SYSTEM_PROMPT
    return DAILY_REPORT_SYSTEM_PROMPT


